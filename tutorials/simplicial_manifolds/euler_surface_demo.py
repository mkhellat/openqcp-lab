def _from_facets(facets: list[tuple[int, ...]]) -> SimplicialComplex:
    frozen = frozenset(frozenset(facet) for facet in facets)
    vertices = frozenset().union(*frozen) if frozen else frozenset()
    return SimplicialComplex(vertices, frozen)


def tetrahedron_boundary() -> SimplicialComplex:
    """Boundary of the 3-simplex on vertices 0, 1, 2, 3.

    Four triangles, six edges, four vertices. This is the closed
    combinatorial 2-sphere already used in notebooks 01 and 02.
    """
    vertices = (0, 1, 2, 3)
    facets = [tuple(v for v in vertices if v != omit) for omit in vertices]
    return _from_facets(facets)


def torus_grid() -> SimplicialComplex:
    """3×3 toroidal grid: opposite sides of the square are identified.

    Each of the nine unit squares is split into two triangles. The
    resulting complex has 9 vertices, 27 edges, and 18 triangles.
    """
    def vid(row: int, col: int) -> int:
        return (row % 3) * 3 + (col % 3)

    facets: list[tuple[int, int, int]] = []
    for row in range(3):
        for col in range(3):
            corner = vid(row, col)
            right = vid(row, col + 1)
            up = vid(row + 1, col)
            diag = vid(row + 1, col + 1)
            facets.append((corner, right, diag))
            facets.append((corner, diag, up))
    return _from_facets(facets)


def torus_seven() -> SimplicialComplex:
    """Minimal 7-vertex triangulation of the torus.

    The cyclic complex generated by (0, 1, 3) and (0, 2, 3) modulo 7.
    It is the Császár triangulation: every pair of vertices is an edge,
    and χ is still 0. The gallery draws the 3×3 grid instead, because
    the square shows the identifications; this complex is the count
    that separates χ from the number of vertices.
    """
    facets: list[tuple[int, int, int]] = []
    for i in range(7):
        facets.append((i, (i + 1) % 7, (i + 3) % 7))
        facets.append((i, (i + 2) % 7, (i + 3) % 7))
    return _from_facets(facets)


def real_projective_plane() -> SimplicialComplex:
    """Minimal 6-vertex triangulation of the real projective plane.

    Ten triangles on the complete graph K₆. χ = 1. A coherent
    orientation does not exist; `orientation_attempt` records the
    first edge where the propagation contradicts itself.
    """
    return _from_facets(
        [
            (0, 1, 2),
            (0, 1, 5),
            (0, 2, 3),
            (0, 3, 4),
            (0, 4, 5),
            (1, 2, 4),
            (1, 3, 4),
            (1, 3, 5),
            (2, 3, 5),
            (2, 4, 5),
        ]
    )


def disjoint_union(left: SimplicialComplex, right: SimplicialComplex) -> SimplicialComplex:
    """Vertex-disjoint union, shifting `right` past `left`.

    Euler characteristic adds over this union. The classification
    formulas in the notebook are for one component; this helper builds
    the example that shows the sum.
    """
    shift = (max(left.vertices) + 1) if left.vertices else 0
    facets = set(left.facets)
    for face in right.facets:
        facets.add(frozenset(vertex + shift for vertex in face))
    vertices = frozenset().union(*facets) if facets else frozenset()
    return SimplicialComplex(vertices, frozenset(facets))


def face_counts(K: SimplicialComplex) -> tuple[int, int, int]:
    """`(f_0, f_1, f_2)`, the numbers of vertices, edges, and triangles.

    Read from the downward closure. On a pure 2-complex, `f_2` is the
    number of facets. The count does not orient anything and does not
    walk an edge.
    """
    by_dim = K.faces_by_dim()
    return (
        len(by_dim.get(0, ())),
        len(by_dim.get(1, ())),
        len(by_dim.get(2, ())),
    )


def component_count(K: SimplicialComplex) -> int:
    """Components of the 1-skeleton, walked on its adjacency list."""
    adj = K.adjacency_list()
    unseen = set(K.vertices)
    count = 0
    while unseen:
        count += 1
        stack = [unseen.pop()]
        while stack:
            vertex = stack.pop()
            for neighbour in adj[vertex]:
                if neighbour in unseen:
                    unseen.remove(neighbour)
                    stack.append(neighbour)
    return count


def degree_defects(K: SimplicialComplex) -> dict[int, int]:
    """Combinatorial defect `6 - deg(v)` at each vertex.

    On a closed triangulation the defects sum to `6χ`. Six triangles
    around a vertex is the flat pattern; the integer `6 - deg(v)` is
    the taste of discrete curvature used in the notebook. No angles
    are stored.
    """
    return {vertex: 6 - degree for vertex, degree in vertex_degrees(K).items()}


@dataclass(frozen=True)
class OrientationAttempt:
    """Result of propagating triangle orientations across shared edges.

    Meaningful as an orientability test when `K` is already a closed
    combinatorial surface (`closed_surface_link_condition`). Then
    `closed` is true, and `coherent` is false exactly when the surface
    is non-orientable. `conflict_edge` is the first shared edge, in
    sorted vertex order, where the forced direction contradicts the
    sign already chosen.

    `manifold_edges` means every edge lies in one or two triangles. A
    branched edge (three triangles) sets it false and skips the
    propagation. A complex can have `coherent` true and still fail the
    link condition: two disjoint triangles share no edge, so there is
    nothing to contradict.
    """

    manifold_edges: bool
    closed: bool
    coherent: bool
    faces: tuple[tuple[int, int, int], ...] | None
    conflict_edge: tuple[int, int] | None


def _triangular_facets(K: SimplicialComplex) -> tuple[tuple[int, int, int], ...]:
    if K.dimension() != 2 or not K.is_pure(2):
        raise ValueError("orientation propagation expects a pure 2-complex")
    faces = tuple(sorted(tuple(sorted(face)) for face in K.facets))
    if any(len(face) != 3 for face in faces):
        raise ValueError("facets must be triangles")
    return faces


def _directed(face: tuple[int, int, int], sign: int) -> tuple[int, int, int]:
    if sign == 1:
        return face
    origin, left, right = face
    return (origin, right, left)


def _uses_directed(face: tuple[int, int, int], origin: int, dest: int) -> bool:
    a, b, c = face
    return (origin, dest) in ((a, b), (b, c), (c, a))


def orientation_attempt(K: SimplicialComplex) -> OrientationAttempt:
    """Try to orient each triangle so shared edges run in opposite directions.

    Facets are sorted, so the first conflict does not depend on set
    iteration order. The positive sign on a facet is its increasing
    vertex order. A neighbour is forced to use the opposite direction
    on the shared edge. The first contradiction is `conflict_edge`.
    """
    faces = _triangular_facets(K)
    incidence: dict[frozenset[int], list[int]] = {}
    for index, face in enumerate(faces):
        a, b, c = face
        for edge in (frozenset((a, b)), frozenset((b, c)), frozenset((c, a))):
            incidence.setdefault(edge, []).append(index)
    counts = [len(users) for users in incidence.values()]
    manifold_edges = bool(faces) and all(count in (1, 2) for count in counts)
    closed = bool(faces) and all(count == 2 for count in counts)
    if not manifold_edges:
        return OrientationAttempt(False, False, False, None, None)

    signs: list[int | None] = [None] * len(faces)
    conflict_edge: tuple[int, int] | None = None
    for start in range(len(faces)):
        if signs[start] is not None:
            continue
        signs[start] = 1
        queue: deque[int] = deque([start])
        while queue:
            current = queue.popleft()
            sign = signs[current]
            if sign is None:
                continue
            oriented = _directed(faces[current], sign)
            a, b, c = oriented
            for origin, dest in ((a, b), (b, c), (c, a)):
                edge = frozenset((origin, dest))
                for other in incidence[edge]:
                    if other == current:
                        continue
                    required: int | None = None
                    for candidate in (1, -1):
                        if _uses_directed(
                            _directed(faces[other], candidate), dest, origin
                        ):
                            required = candidate
                            break
                    if required is None:
                        raise RuntimeError("shared edge is missing from the neighbour")
                    if signs[other] is None:
                        signs[other] = required
                        queue.append(other)
                    elif signs[other] != required and conflict_edge is None:
                        conflict_edge = (min(origin, dest), max(origin, dest))
    if conflict_edge is not None or any(sign is None for sign in signs):
        return OrientationAttempt(True, closed, False, None, conflict_edge)
    oriented_faces = tuple(
        _directed(face, sign)  # type: ignore[arg-type]
        for face, sign in zip(faces, signs)
    )
    return OrientationAttempt(True, closed, True, oriented_faces, None)


def coherently_orientable(K: SimplicialComplex) -> bool:
    """Whether `K` is a closed combinatorial surface with a coherent orientation.

    The link condition is the gate from notebook 02. Orientation is the
    extra bit the classification sketch uses. A complex that fails the
    link condition returns false, including a pinched vertex whose
    triangles happen to have no shared edge to contradict.
    """
    if not closed_surface_link_condition(K):
        return False
    return orientation_attempt(K).coherent


def classification_label(K: SimplicialComplex) -> str:
    """Homeomorphism-type label for a connected closed combinatorial surface.

    Orientable case: χ = 2 − 2g, and the label carries the genus.
    Non-orientable case: χ = 2 − k, and the label carries the number of
    crosscaps. Several components are reported as a component count and
    χ, because those two formulas are for one component.
    """
    if not closed_surface_link_condition(K):
        return "not a closed combinatorial surface"
    chi = euler_characteristic(K)
    components = component_count(K)
    if components != 1:
        return f"{components} components, χ={chi}"
    if orientation_attempt(K).coherent:
        genus = (2 - chi) // 2
        return f"orientable, genus {genus}, χ={chi}"
    crosscaps = 2 - chi
    noun = "crosscap" if crosscaps == 1 else "crosscaps"
    return f"non-orientable, {crosscaps} {noun}, χ={chi}"


def surface_report(name: str, K: SimplicialComplex) -> str:
    """Plain-text reading printed under the gallery figure."""
    vertices, edges, faces = face_counts(K)
    chi = euler_characteristic(K)
    defects = degree_defects(K)
    defect_sum = sum(defects.values())
    defect_text = ", ".join(
        f"{vertex}:{defects[vertex]}" for vertex in sorted(defects)
    )
    lines = [
        name,
        f"V={vertices}  E={edges}  F={faces}",
        f"{vertices} - {edges} + {faces} = {chi}",
        f"euler_characteristic={chi}",
        f"closed_surface_link_condition={closed_surface_link_condition(K)}",
        f"components={component_count(K)}",
        f"classification: {classification_label(K)}",
        f"sum (6 - deg v) = {defect_sum}",
        f"6χ = {6 * chi}",
        f"defects {defect_text}",
    ]
    return "\n".join(lines)


