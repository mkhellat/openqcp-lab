def _hex_rgb(color: str) -> tuple[float, float, float]:
    value = color.lstrip("#")
    return tuple(int(value[i : i + 2], 16) / 255.0 for i in (0, 2, 4))


def draw_surface(key: str, *, elev: float = 22.0, azim: float = -72.0):
    """Draw one gallery surface and return `(figure, report text)`."""
    item = _GALLERY[key]
    fig = plt.figure(figsize=(7.2, 5.6))
    fig.patch.set_facecolor("white")
    if item.ambient == 3:
        ax = fig.add_subplot(111, projection="3d", computed_zorder=False)
        _draw_sphere(ax, elev=elev, azim=azim)
    else:
        ax = fig.add_subplot(111)
        if key == "torus":
            _draw_torus(ax)
        else:
            _draw_rp2(ax)
    vertices, edges, faces = face_counts(item.complex)
    chi = euler_characteristic(item.complex)
    ax.set_title(
        f"{item.title}    {vertices} − {edges} + {faces} = {chi}",
        fontsize=13,
        color="#222222",
        pad=8,
    )
    fig.text(
        0.5,
        0.02,
        item.caption,
        ha="center",
        va="bottom",
        fontsize=9,
        color="#333333",
    )
    fig.subplots_adjust(left=0.02, right=0.98, bottom=0.08, top=0.90)
    return fig, surface_report(item.title, item.complex)


def launch_euler_surface_demo() -> None:
    """Build the gallery widget and draw the tetrahedron boundary.

    The dropdown switches sphere, torus, and RP². The printed lines are
    `face_counts`, `euler_characteristic`, the link gate from notebook
    02, the classification label, and the degree defects. Call this
    from a hidden notebook cell.
    """
    busy = {"on": False}
    preset = W.Dropdown(
        options=[(item.menu, item.key) for item in gallery_items()],
        value="sphere",
        description="surface",
        style={"description_width": "70px"},
        layout=W.Layout(width="460px"),
    )
    elev_s = W.FloatSlider(
        value=22.0,
        min=-90.0,
        max=90.0,
        step=1.0,
        description="elev",
        continuous_update=False,
        style={"description_width": "40px"},
        layout=W.Layout(width="320px"),
    )
    azim_s = W.FloatSlider(
        value=-72.0,
        min=-180.0,
        max=180.0,
        step=1.0,
        description="azim",
        continuous_update=False,
        style={"description_width": "40px"},
        layout=W.Layout(width="320px"),
    )
    status = W.HTML(value="")
    out = W.Output()
    cam_box = W.VBox(
        [
            W.HTML("<b>camera</b> — sphere only"),
            W.HBox([elev_s, azim_s]),
        ]
    )

    def _sync_camera(key: str) -> None:
        if _GALLERY[key].ambient == 3:
            cam_box.layout.display = None
        else:
            cam_box.layout.display = "none"

    def _redraw(_=None) -> None:
        if busy["on"]:
            return
        busy["on"] = True
        try:
            key = preset.value
            with out:
                clear_output(wait=True)
                fig, report = draw_surface(
                    key,
                    elev=float(elev_s.value),
                    azim=float(azim_s.value),
                )
                display(fig)
                plt.close(fig)
                print(report)
            item = _GALLERY[key]
            vertices, edges, faces = face_counts(item.complex)
            chi = euler_characteristic(item.complex)
            status.value = (
                f"<b>{item.title}</b> — "
                f"{vertices} − {edges} + {faces} = {chi}"
            )
        except Exception as err:
            status.value = (
                f"<span style='color:#a00'><b>draw error:</b> {err}</span>"
            )
            with out:
                clear_output(wait=True)
                print("draw error:", err)
        finally:
            busy["on"] = False

    hint = W.HTML(
        "χ is <code>V − E + F</code> from the downward closure, the same "
        "integer as <code>euler_characteristic</code>. The torus picture "
        "repeats boundary vertices; the complex still has nine. The RP² "
        "circle identifies antipodal points. Crossings in that disk are "
        "the drawing."
    )
    ui = W.VBox(
        [
            W.HTML(
                "<b>Euler characteristic of three closed surfaces</b> — "
                "edit <code>euler_surface_demo.py</code> to change the drawings."
            ),
            preset,
            hint,
            cam_box,
            status,
            out,
        ]
    )
    _sync_camera(preset.value)
    preset.observe(_redraw, names="value")
    elev_s.observe(_redraw, names="value")
    azim_s.observe(_redraw, names="value")
    display(ui)
    _redraw()
