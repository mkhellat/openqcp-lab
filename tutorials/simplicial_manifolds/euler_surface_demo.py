def _frame(ax, points: list[np.ndarray], ambient: int, *, pad: float) -> None:
    pts = np.vstack(points)
    lo = pts.min(axis=0)
    hi = pts.max(axis=0)
    center = 0.5 * (lo + hi)
    span = np.maximum(hi - lo, 0.85)
    lo = center - 0.5 * span - pad
    hi = center + 0.5 * span + pad
    ax.set_xlim(lo[0], hi[0])
    ax.set_ylim(lo[1], hi[1])
    if ambient == 2:
        ax.set_aspect("equal", adjustable="box")
        ax.set_axis_off()
        return
    ax.set_zlim(lo[2], hi[2])
    ax.set_box_aspect((1.0, 1.0, 1.0))
    ax.set_axis_off()


def _draw_sphere(ax, *, elev: float, azim: float) -> None:
    complex_ = _GALLERY["sphere"].complex
    tris = [np.vstack([_TETRA[v] for v in sorted(face)]) for face in complex_.facets]
    rgba = (*_hex_rgb(_FACE), 0.35)
    ax.add_collection3d(
        Poly3DCollection(
            tris,
            facecolors=[rgba] * len(tris),
            edgecolors="none",
        )
    )
    for edge in complex_.faces_by_dim().get(1, ()):
        a, b = (int(v) for v in sorted(edge))
        p, q = _TETRA[a], _TETRA[b]
        ax.plot(
            [p[0], q[0]],
            [p[1], q[1]],
            [p[2], q[2]],
            color=_EDGE,
            lw=1.4,
            solid_capstyle="round",
        )
    center = sum(_TETRA.values()) / 4.0
    for vertex, point in _TETRA.items():
        ax.scatter(
            [point[0]],
            [point[1]],
            [point[2]],
            s=36,
            c=_VERTEX,
            depthshade=False,
        )
        direction = point - center
        outward = point + 0.28 * direction / np.linalg.norm(direction)
        ax.text(
            outward[0],
            outward[1],
            outward[2],
            str(vertex),
            fontsize=11,
            color="#222222",
            ha="center",
            va="center",
        )
    ax.view_init(elev=elev, azim=azim)
    _frame(ax, list(_TETRA.values()), 3, pad=0.35)


def _grid_xy(vertex: int) -> np.ndarray:
    row, col = divmod(vertex, 3)
    return np.array([float(col), float(row)])


def _unwrap(vertices: tuple[int, ...]) -> list[np.ndarray]:
    """Place one grid triangle so a wrapped edge does not cross the square.

    Coordinates live in {0, 1, 2}. A neighbour that crossed the
    identification appears at distance 2. Shift the low side by 3 so
    the triangle sits on the boundary it actually crosses. The shifted
    copy is a drawing of a vertex the complex already counted.
    """
    pts = [_grid_xy(vertex) for vertex in vertices]
    for axis in (0, 1):
        coords = [float(point[axis]) for point in pts]
        if max(coords) - min(coords) >= 1.5:
            low = min(coords)
            for point in pts:
                if point[axis] == low:
                    point[axis] += 3.0
    span = max(
        max(float(point[axis]) for point in pts) - min(float(point[axis]) for point in pts)
        for axis in (0, 1)
    )
    if span > 1.01:
        raise RuntimeError("grid triangle did not unwrap into the fundamental domain")
    return pts


def _draw_torus(ax) -> None:
    complex_ = _GALLERY["torus"].complex
    polys = []
    ghosts: list[tuple[np.ndarray, int]] = []
    for face in complex_.facets:
        ordered = tuple(sorted(face))
        pts = _unwrap(ordered)
        polys.append(np.vstack(pts))
        for vertex, point in zip(ordered, pts):
            if point[0] >= 2.5 or point[1] >= 2.5:
                ghosts.append((point.copy(), vertex))
        for i in range(3):
            p, q = pts[i], pts[(i + 1) % 3]
            ax.plot(
                [p[0], q[0]],
                [p[1], q[1]],
                color=_EDGE,
                lw=1.15,
                solid_capstyle="round",
                zorder=2,
            )
    rgba = (*_hex_rgb(_FACE), 0.92)
    ax.add_collection(
        PolyCollection(
            polys,
            facecolors=[rgba] * len(polys),
            edgecolors="none",
            zorder=1,
        )
    )
    square = np.array([[0, 0], [3, 0], [3, 3], [0, 3], [0, 0]], dtype=float)
    ax.plot(square[:, 0], square[:, 1], color=_FRAME, lw=1.3, zorder=3)
    for vertex in range(9):
        point = _grid_xy(vertex)
        ax.scatter([point[0]], [point[1]], s=36, c=_VERTEX, zorder=4)
        ax.annotate(
            str(vertex),
            xy=(point[0], point[1]),
            xytext=(4, 4),
            textcoords="offset points",
            fontsize=10,
            color="#222222",
            zorder=5,
        )
    seen: set[tuple[int, int, int]] = set()
    for point, vertex in ghosts:
        key = (vertex, int(round(point[0])), int(round(point[1])))
        if key in seen:
            continue
        seen.add(key)
        ax.scatter(
            [point[0]],
            [point[1]],
            s=36,
            facecolors="white",
            edgecolors=_GHOST,
            linewidths=1.2,
            zorder=4,
        )
        ax.annotate(
            str(vertex),
            xy=(point[0], point[1]),
            xytext=(4, 4),
            textcoords="offset points",
            fontsize=10,
            color=_GHOST,
            zorder=5,
        )
    _identify_arrows(ax)
    _frame(ax, [np.array([0.0, 0.0]), np.array([3.0, 3.0])], 2, pad=0.55)


def _identify_arrows(ax) -> None:
    """Matching arrows on opposite sides of the fundamental square."""
    pairs = (
        (((0.55, -0.28), (1.35, -0.28)), ((0.55, 3.28), (1.35, 3.28)), "#b45309"),
        (((-0.28, 0.55), (-0.28, 1.35)), ((3.28, 0.55), (3.28, 1.35)), "#1d4e89"),
    )
    for start, end, color in pairs:
        for (x0, y0), (x1, y1) in (start, end):
            ax.annotate(
                "",
                xy=(x1, y1),
                xytext=(x0, y0),
                arrowprops={"arrowstyle": "->", "color": color, "lw": 1.2},
                annotation_clip=False,
            )


def _rp2_points() -> dict[int, np.ndarray]:
    """Deterministic relaxation of the 6-vertex complex into a disk."""
    pos = {}
    for vertex in range(6):
        angle = 2.0 * math.pi * vertex / 6.0 + 0.35
        radius = 0.2 if vertex == 0 else 0.62
        pos[vertex] = np.array([radius * math.cos(angle), radius * math.sin(angle)])
    edges = list(real_projective_plane().faces_by_dim()[1])
    ids = list(range(6))
    for _ in range(80):
        disp = {vertex: np.zeros(2) for vertex in ids}
        for i, left in enumerate(ids):
            for right in ids[i + 1 :]:
                delta = pos[left] - pos[right]
                dist = float(np.linalg.norm(delta)) + 1e-6
                push = 0.02 * delta / (dist * dist)
                disp[left] += push
                disp[right] -= push
        for edge in edges:
            left, right = tuple(sorted(edge))
            delta = pos[right] - pos[left]
            disp[left] += 0.08 * delta
            disp[right] -= 0.08 * delta
        for vertex in ids:
            pos[vertex] = pos[vertex] + disp[vertex]
    center = sum(pos.values()) / 6.0
    for vertex in ids:
        pos[vertex] = pos[vertex] - center
    scale = max(float(np.linalg.norm(point)) for point in pos.values())
    for vertex in ids:
        pos[vertex] = pos[vertex] / scale * 0.72
    return pos


